    /** Registro ufficiale. */
    SolisRegister(int address, RegisterType type, int decimals, String unit, Category category, String description) {
        this(address, type, decimals, unit, category, description, false);
    }

    /** Registro ufficiale per cui 0xFFFF significa "non disponibile". */
    SolisRegister(int address, RegisterType type, int decimals, String unit, Category category, String description,
                  boolean ffffMeansUnavailable) {
        this(address, type, decimals, unit, category, description, ffffMeansUnavailable,
                RegisterSource.OFFICIAL, null, null);
    }

    /**
     * Registro riservato nel protocollo ufficiale ma interpretato da una fonte pubblica (NON ufficiale). La descrizione
     * è "nome pubblico: descrizione"; provenienza e fonte restano in {@link #source()} e {@link #reference()}.
     */
    SolisRegister(int address, RegisterType type, int decimals, String unit, Category category, String description,
                  RegisterSource source, String publicName, String reference) {
        this(address, type, decimals, unit, category,
                "%s: %s".formatted(publicName, description),
                false, source, publicName, reference);
    }

    /** Registro riservato senza significato noto: esposto come valore grezzo a 16 bit. */
    SolisRegister(int address) {
        this(address, U16, 0, "", Category.RESERVED, "Riservato nel protocollo Solis, significato non documentato",
                false, RegisterSource.RESERVED, null, null);
    }

    SolisRegister(int address, RegisterType type, int decimals, String unit, Category category, String description,
                  boolean ffffMeansUnavailable, RegisterSource source, String publicName, String reference) {
        this.address = address;
        this.type = type;
        this.decimals = decimals;
        this.unit = unit;
        this.category = category;
        this.description = description;
        this.ffffMeansUnavailable = ffffMeansUnavailable;
        this.source = source;
        this.publicName = publicName;
        this.reference = reference;
    }

    public int address() {
        return address;
    }

    public RegisterType type() {
        return type;
    }

    public int words() {
        return type.defaultWords();
    }

    /** Indirizzo dell'ultima word occupata dal registro. */
    public int lastAddress() {
        return address + words() - 1;
    }

    public int decimals() {
        return decimals;
    }

    public String unit() {
        return unit;
    }

    public Category category() {
        return category;
    }

    public String description() {
        return description;
    }

    /** Holding register (43xxx): si legge con la funzione 0x03 e si può scrivere. Gli altri sono input register. */
    public boolean holding() {
        return address >= 40000;
    }

    public RegisterAccess access() {
        return holding() ? RegisterAccess.READ_WRITE : RegisterAccess.READ_ONLY;
    }

    public RegisterSource source() {
        return source;
    }

    /** Nome usato dalla fonte pubblica (solo per i registri non ufficiali). */
    public String publicName() {
        return publicName;
    }

    /** Fonte pubblica della definizione (solo per i registri non ufficiali). */
    public String reference() {
        return reference;
    }

    /** Se true, il valore grezzo 0xFFFF indica "dato non disponibile" e viene restituito come null. */
    public boolean ffffMeansUnavailable() {
        return ffffMeansUnavailable;
    }
